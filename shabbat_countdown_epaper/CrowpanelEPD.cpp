static void crowLoadLut(const uint8_t *r20, const uint8_t *r21, const uint8_t *r22, const uint8_t *r23, const uint8_t *r24) {
  crowWrReg(0x20);
  for (uint8_t i = 0; i < 42; i++) crowWrData8(r20[i]);
  crowWrReg(0x21);
  for (uint8_t i = 0; i < 42; i++) crowWrData8(r21[i]);
  crowWrReg(0x22);
  for (uint8_t i = 0; i < 42; i++) crowWrData8(r22[i]);
  crowWrReg(0x23);
  for (uint8_t i = 0; i < 42; i++) crowWrData8(r23[i]);
  crowWrReg(0x24);
  for (uint8_t i = 0; i < 42; i++) crowWrData8(r24[i]);
}

static void crowLutGC() { crowLoadLut(lut_R20_GC, lut_R21_GC, lut_R22_GC, lut_R23_GC, lut_R24_GC); }
static void crowLutDU() { crowLoadLut(lut_R20_DU, lut_R21_DU, lut_R22_DU, lut_R23_DU, lut_R24_DU); }

// EPD_Update() in Elecrow's code: the actual trigger for this controller —
// NOT the 0x20 "activate display update sequence" command GxEPD2 uses.
static void crowUpdate() {
  crowWrReg(0x17);
  crowWrData8(0xA5);
  crowReadBusy();
}

// EPD_Init() in Elecrow's code, byte-for-byte.
