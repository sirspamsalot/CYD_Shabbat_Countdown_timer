void crowEpdInit() {
  crowGpioInit();
  crowReset();
  crowEpdRegisterInit();
}

static void crowDisplayWithLut(const uint8_t *buffer, void (*loadLut)()) {
  crowWrReg(0x50);
  crowWrData8(0xD7);
  crowWrReg(0x13);
  for (uint32_t i = 0; i < (uint32_t)CROW_EPD_BUFFER_BYTES; i++) {
    crowWrData8(buffer[i]);
  }
  loadLut();
  crowUpdate();
}

void crowEpdDisplay(const uint8_t *buffer) {
  crowDisplayWithLut(buffer, crowLutGC);
}

void crowEpdDisplayPartial(const uint8_t *buffer) {
  crowDisplayWithLut(buffer, crowLutDU);
}
