// CrowpanelEPD.cpp — see CrowpanelEPD.h for the full explanation. This is a
// direct port of Elecrow's own EPD.cpp / EPD_SPI.cpp (the proven-working
// driver behind their 4.2_Example3_PWR example), trimmed to just init +
// full-buffer display, with the pin numbers and bit-bang SPI kept exactly
// as they were in that original code (same pins this sketch already uses:
// CS=45 DC=46 RST=47 BUSY=48 SCLK=12 MOSI=11).

#include "CrowpanelEPD.h"

// ---- pins (kept private to this file; the .ino has its own EPD_* macros
// with the same values for its own reference, but these are independent) ----
#define CROW_SCK   12
#define CROW_MOSI  11
#define CROW_RES   47
#define CROW_DC    46
#define CROW_CS    45
#define CROW_BUSY  48

#define CROW_SCK_Clr()  digitalWrite(CROW_SCK, LOW)
#define CROW_SCK_Set()  digitalWrite(CROW_SCK, HIGH)
#define CROW_MOSI_Clr() digitalWrite(CROW_MOSI, LOW)
#define CROW_MOSI_Set() digitalWrite(CROW_MOSI, HIGH)
#define CROW_RES_Clr()  digitalWrite(CROW_RES, LOW)
#define CROW_RES_Set()  digitalWrite(CROW_RES, HIGH)
#define CROW_DC_Clr()   digitalWrite(CROW_DC, LOW)
#define CROW_DC_Set()   digitalWrite(CROW_DC, HIGH)
#define CROW_CS_Clr()   digitalWrite(CROW_CS, LOW)
#define CROW_CS_Set()   digitalWrite(CROW_CS, HIGH)
#define CROW_ReadBUSY() digitalRead(CROW_BUSY)

// ---- bit-banged ("software") SPI — identical approach to Elecrow's own
// EPD_WR_Bus(), the thing that actually made the panel respond ----
static void crowWrBus(uint8_t dat) {
  CROW_CS_Clr();
  for (uint8_t i = 0; i < 8; i++) {
    CROW_SCK_Clr();
    if (dat & 0x80) CROW_MOSI_Set();
    else CROW_MOSI_Clr();
    CROW_SCK_Set();
    dat <<= 1;
  }
  CROW_CS_Set();
}

static void crowWrReg(uint8_t reg) {
  CROW_DC_Clr();
  crowWrBus(reg);
  CROW_DC_Set();
}

static void crowWrData8(uint8_t dat) {
  CROW_DC_Set();
  crowWrBus(dat);
  CROW_DC_Set();
}

static void crowGpioInit() {
  pinMode(CROW_SCK, OUTPUT);
  pinMode(CROW_MOSI, OUTPUT);
  pinMode(CROW_RES, OUTPUT);
  pinMode(CROW_DC, OUTPUT);
  pinMode(CROW_CS, OUTPUT);
  pinMode(CROW_BUSY, INPUT);
}

static void crowReset() {
  CROW_RES_Set();
  delay(10);
  CROW_RES_Clr();
  delay(100);
  CROW_RES_Set();
  delay(100);
}

// Bounded busy-wait: Elecrow's own EPD_ReadBusy() loops forever, but this
// sketch has relied throughout its e-paper bring-up on a "Busy Timeout!"
// diagnostic to tell a genuinely stuck panel from a working one, so that
// behavior is kept here (10s bound) rather than risking a permanent hang.
static void crowReadBusy() {
  unsigned long start = millis();
  while (CROW_ReadBUSY() != 0) {
    if (millis() - start > 10000UL) {
      Serial.println(F("Busy Timeout!"));
      break;
    }
    delay(1);
  }
}

